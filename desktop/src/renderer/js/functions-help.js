/** The function call the caret is inside, with the argument index @param {string} text @param {number} caret */
export function callAt(text, caret) {
  const s = text.slice(0, caret);
  let depth = 0, arg = 0, inStr = false;
  for (let i = s.length - 1; i >= 0; i--) {
    const ch = s[i];
    if (ch === '"') { inStr = !inStr; continue; }
    if (inStr) continue;
    if (ch === ')') depth++;
    else if (ch === '(') {
      if (depth === 0) {
        const m = /([A-Za-z_][A-Za-z0-9_.]*)\s*$/.exec(s.slice(0, i));
        return m ? { name: m[1].toUpperCase(), arg } : null;
      }
      depth--;
    } else if ((ch === ',' || ch === ';') && depth === 0) arg++;
  }
  return null;
}
